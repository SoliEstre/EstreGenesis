#!/usr/bin/env node
/**
 * sync-registry-status.mjs — publish the subscaler model-profile status on the Superscalar promo page.
 *
 * Why this is generated: the promo pages that were hand-maintained froze (module counts said six
 * while eight existed; a timeline stopped months earlier) because nothing forced them to move when
 * the source moved. The model registry changes on its own cadence, so its public status block is
 * DERIVED from plugins/superscalar/model-registry.json and gated by --check (the maintenance
 * checker runs it on every cut). Nothing in the block depends on today's date — only on the
 * registry — so --check is deterministic.
 *
 * Usage:
 *   node scripts/sync-registry-status.mjs --write   # (re)write the block in docs/superscalar.html
 *   node scripts/sync-registry-status.mjs --check   # exit 1 if the committed block differs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const INNER = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const REG = path.join(INNER, 'plugins', 'superscalar', 'model-registry.json');
const PAGE = path.join(INNER, 'docs', 'superscalar.html');
const BEGIN = '<!-- BEGIN REGISTRY-STATUS (generated by scripts/sync-registry-status.mjs --write — do not hand-edit) -->';
const END = '<!-- END REGISTRY-STATUS -->';
const ANCHOR = '<section id="install-superscalar">';
const REPO = 'https://github.com/SoliEstre/EstreGenesis/blob/main/plugins/superscalar/model-registry.json';
const NEW_WINDOW_DAYS = 31;

const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const dayNum = (d) => Math.floor(Date.parse(d + 'T00:00:00Z') / 864e5);

function render(reg) {
  const tierOrder = reg.tiers.map((t) => t.tier);
  const released = (m) => ((m.notes || '').match(/Released (\d{4}-\d{2}-\d{2})/) || [])[1] || '';
  const rows = reg.models
    .map((m, i) => ({ m, i, rel: released(m) }))
    .sort((a, b) => tierOrder.indexOf(a.m.tier) - tierOrder.indexOf(b.m.tier) || a.i - b.i);
  const providers = [...new Set(reg.models.map((m) => m.provider))];
  const asOfDay = dayNum(reg.asOf);
  const isNew = (rel) => rel && asOfDay - dayNum(rel) >= 0 && asOfDay - dayNum(rel) <= NEW_WINDOW_DAYS;
  const newCount = rows.filter((r) => isNew(r.rel)).length;
  const perTier = tierOrder.map((t) => `${esc(t.split(' · ')[0])} ${rows.filter((r) => r.m.tier === t).length}`).join(' · ');
  const L = [];
  L.push(BEGIN);
  L.push('    <section id="model-profile-status">');
  L.push('      <h2 data-en="Model profile status" data-ko="모델 프로필 갱신 현황">Model profile status</h2>');
  L.push(`      <p data-en="The /subscaler tiers read a dated registry rather than a model list baked into the spec — models move monthly, the tier vocabulary does not. This block is generated from that registry on every release, so it cannot lag behind it." data-ko="/subscaler 의 티어는 스펙에 박힌 모델 목록이 아니라 날짜가 붙은 레지스트리를 읽어요 — 모델은 달마다 바뀌고 티어 어휘는 안 바뀌니까요. 이 블록은 매 릴리스마다 그 레지스트리에서 생성돼서 레지스트리보다 뒤처질 수 없어요.">The /subscaler tiers read a dated registry rather than a model list baked into the spec. This block is generated from that registry on every release.</p>`);
  L.push('      <ul>');
  L.push(`        <li data-en="Last researched: ${esc(reg.asOf)} · next scheduled re-check: ${esc(reg.revisit.date)}" data-ko="마지막 조사: ${esc(reg.asOf)} · 다음 재조사 예정: ${esc(reg.revisit.date)}">Last researched: ${esc(reg.asOf)} · next scheduled re-check: ${esc(reg.revisit.date)}</li>`);
  L.push(`        <li data-en="${reg.models.length} models from ${providers.length} providers (${perTier}) · ${newCount} released within ${NEW_WINDOW_DAYS} days of that date" data-ko="모델 ${reg.models.length}개 · 제공사 ${providers.length}곳 (${perTier}) · 조사일 기준 ${NEW_WINDOW_DAYS}일 안에 출시된 모델 ${newCount}개">${reg.models.length} models from ${providers.length} providers (${perTier}) · ${newCount} released within ${NEW_WINDOW_DAYS} days of that date</li>`);
  L.push(`        <li data-en="Open items on the watchlist: ${reg.revisit.watchlist.length} · recorded caveats (what was not verified): ${reg.caveats.length}" data-ko="감시 목록: ${reg.revisit.watchlist.length}건 · 기록된 주의사항(확인하지 못한 것): ${reg.caveats.length}건">Open items on the watchlist: ${reg.revisit.watchlist.length} · recorded caveats (what was not verified): ${reg.caveats.length}</li>`);
  L.push('      </ul>');
  L.push('      <div style="overflow-x:auto">');
  L.push('      <table class="data">');
  L.push('        <thead><tr><th data-en="Tier" data-ko="티어">Tier</th><th data-en="Provider" data-ko="제공사">Provider</th><th data-en="Model" data-ko="모델">Model</th><th data-en="API id" data-ko="API id">API id</th><th data-en="Released" data-ko="출시">Released</th><th data-en="Source" data-ko="출처">Source</th></tr></thead>');
  L.push('        <tbody>');
  for (const { m, rel } of rows) {
    const flag = isNew(rel) ? ' <span class="badge" data-en="new" data-ko="신규">new</span>' : '';
    let host = '';
    try { host = new URL(m.confirmedBy).host; } catch { host = 'source'; }
    L.push(`          <tr><td>${esc(m.tier)}</td><td>${esc(m.provider)}</td><td>${esc(m.displayName)}${flag}</td><td><code>${esc(m.apiModelId)}</code></td><td>${esc(rel || '—')}</td><td><a href="${esc(m.confirmedBy)}" target="_blank" rel="noopener">${esc(host)}</a></td></tr>`);
  }
  L.push('        </tbody>');
  L.push('      </table>');
  L.push('      </div>');
  L.push(`      <p data-en="Full rows (context window, pricing, effort values, per-harness binding keys, watchlist and caveats) live in the registry file itself: model-registry.json." data-ko="전체 행(컨텍스트 창 · 가격 · effort 값 · 하네스별 바인딩 키 · 감시 목록 · 주의사항)은 레지스트리 파일에 있어요: model-registry.json."><a href="${REPO}" target="_blank" rel="noopener">model-registry.json</a></p>`);
  L.push('    </section>');
  L.push(END);
  return L.join('\n');
}

const mode = process.argv[2];
const reg = JSON.parse(fs.readFileSync(REG, 'utf8'));
const block = render(reg);
const page = fs.readFileSync(PAGE, 'utf8');
const b = page.indexOf(BEGIN), e = page.indexOf(END);
let next;
if (b >= 0 && e > b) next = page.slice(0, b) + block + page.slice(e + END.length);
else {
  const a = page.indexOf(ANCHOR);
  if (a < 0) { console.error('anchor not found: ' + ANCHOR); process.exit(2); }
  next = page.slice(0, a) + block + '\n\n    ' + page.slice(a);
}
if (mode === '--write') {
  fs.writeFileSync(PAGE, next);
  console.log(`[write] docs/superscalar.html registry-status block — asOf ${reg.asOf}, ${reg.models.length} models`);
} else if (mode === '--check') {
  if (next !== page) { console.error(`DRIFT docs/superscalar.html registry-status block != model-registry.json (asOf ${reg.asOf}) — run: node scripts/sync-registry-status.mjs --write`); process.exit(1); }
  console.log(`[check] registry-status block in sync (asOf ${reg.asOf}, ${reg.models.length} models)`);
} else {
  console.log('usage: node scripts/sync-registry-status.mjs --write | --check');
}
